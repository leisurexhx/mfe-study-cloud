"""Server-side analysis provider boundary."""

from __future__ import annotations

import base64
import time
from dataclasses import dataclass
from typing import Any, Protocol

from mfe_study_cloud.analysis.errors import (
    ProviderConfigurationError,
    ProviderDisabledError,
    ProviderRefusalError,
    ProviderSchemaError,
    ProviderTransientError,
)
from mfe_study_cloud.analysis.models import (
    PROMPT_VERSION,
    SCHEMA_VERSION,
    BatchAnalysisOutput,
    BilingualTerm,
    Connections,
    FormulaExplanation,
    PageAnalysisOutput,
)
from mfe_study_cloud.analysis.prompt import SYSTEM_PROMPT, batch_user_prompt
from mfe_study_cloud.config import Settings


@dataclass(frozen=True, slots=True)
class AnalysisRequest:
    document_id: str
    document_title: str
    pdf_bytes: bytes
    first_page: int
    last_page: int


@dataclass(frozen=True, slots=True)
class AnalysisResult:
    output: BatchAnalysisOutput
    provider: str
    model: str
    response_id: str | None
    prompt_version: str
    schema_version: str
    input_tokens: int
    output_tokens: int
    latency_ms: int


class AnalysisProvider(Protocol):
    name: str

    def analyze(self, request: AnalysisRequest) -> AnalysisResult: ...


class DisabledProvider:
    name = "disabled"

    def analyze(self, request: AnalysisRequest) -> AnalysisResult:
        del request
        raise ProviderDisabledError(
            "Analysis is disabled. Configure the fake provider for a demo or a server provider."
        )


class FakeAnalysisProvider:
    """Deterministic, network-free provider used by demos, tests, and CI."""

    name = "fake"

    def analyze(self, request: AnalysisRequest) -> AnalysisResult:
        started = time.perf_counter()
        pages = []
        for page_number in range(request.first_page, request.last_page + 1):
            pages.append(
                PageAnalysisOutput(
                    page_number=page_number,
                    original_text=f"Anonymous demo content from page {page_number}.",
                    chinese_translation=f"第 {page_number} 页匿名演示内容。",
                    page_overview=(
                        "A deterministic no-cost analysis generated by the fake provider."
                    ),
                    detailed_explanation="用于验证上传、任务、入库和阅读流程，不代表真实模型输出。",
                    formula_explanation=FormulaExplanation(has_formula=False, formulas=[]),
                    key_points=["Fake provider output", "No external network request"],
                    common_mistakes=[],
                    bilingual_terms=[
                        BilingualTerm(
                            term_en="demo",
                            term_zh="演示",
                            definition="A safe deterministic example.",
                            context="Generated without a paid provider.",
                        )
                    ],
                    connections=Connections(previous=[], next=[]),
                    extensions=[],
                    confidence=1.0,
                    needs_review=False,
                )
            )
        elapsed = round((time.perf_counter() - started) * 1000)
        return AnalysisResult(
            output=BatchAnalysisOutput(pages=pages),
            provider=self.name,
            model="fake-v1",
            response_id=None,
            prompt_version=PROMPT_VERSION,
            schema_version=SCHEMA_VERSION,
            input_tokens=0,
            output_tokens=0,
            latency_ms=elapsed,
        )


class OpenAIResponsesProvider:
    """OpenAI Responses API implementation; constructed only in trusted server processes."""

    name = "openai"

    def __init__(self, settings: Settings, *, client: Any | None = None) -> None:
        model = settings.openai_model
        if not settings.openai_api_key or not model:
            raise ProviderConfigurationError(
                "OpenAI provider requires server-side OPENAI_API_KEY and OPENAI_MODEL."
            )
        self._settings = settings
        self._model = model
        if client is None:
            from openai import OpenAI

            client = OpenAI(api_key=settings.openai_api_key.get_secret_value())
        self._client = client

    def analyze(self, request: AnalysisRequest) -> AnalysisResult:
        if len(request.pdf_bytes) > self._settings.analysis_max_input_bytes:
            raise ProviderConfigurationError(
                "PDF batch exceeds the configured provider byte limit."
            )
        encoded = base64.b64encode(request.pdf_bytes).decode("ascii")
        started = time.perf_counter()
        try:
            response = self._client.responses.parse(
                model=self._model,
                reasoning={"effort": self._settings.openai_reasoning_effort},
                max_output_tokens=self._settings.analysis_max_output_tokens,
                store=False,
                input=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {
                        "role": "user",
                        "content": [
                            {
                                "type": "input_file",
                                "filename": (
                                    f"document-{request.document_id}-"
                                    f"pages-{request.first_page}-{request.last_page}.pdf"
                                ),
                                "file_data": f"data:application/pdf;base64,{encoded}",
                                "detail": self._settings.openai_pdf_detail,
                            },
                            {
                                "type": "input_text",
                                "text": batch_user_prompt(
                                    first_page=request.first_page,
                                    last_page=request.last_page,
                                    document_title=request.document_title,
                                ),
                            },
                        ],
                    },
                ],
                text_format=BatchAnalysisOutput,
            )
        except (TimeoutError, ConnectionError) as exc:
            raise ProviderTransientError("OpenAI request failed transiently.") from exc
        except Exception as exc:
            error_name = type(exc).__name__.lower()
            if "ratelimit" in error_name or "timeout" in error_name or "connection" in error_name:
                raise ProviderTransientError("OpenAI request failed transiently.") from exc
            raise
        elapsed = round((time.perf_counter() - started) * 1000)

        parsed = getattr(response, "output_parsed", None)
        if parsed is None:
            refusal = _response_refusal(response)
            if refusal:
                raise ProviderRefusalError("The provider refused this PDF batch.")
            raise ProviderSchemaError("Provider response did not include parsed structured output.")
        if not isinstance(parsed, BatchAnalysisOutput):
            try:
                parsed = BatchAnalysisOutput.model_validate(parsed)
            except Exception as exc:
                raise ProviderSchemaError("Provider output failed schema validation.") from exc
        expected = list(range(request.first_page, request.last_page + 1))
        actual = [page.page_number for page in parsed.pages]
        if actual != expected:
            raise ProviderSchemaError(
                f"Provider returned page numbers {actual}; expected {expected}."
            )
        usage = getattr(response, "usage", None)
        return AnalysisResult(
            output=parsed,
            provider=self.name,
            model=self._model,
            response_id=str(getattr(response, "id", "")) or None,
            prompt_version=PROMPT_VERSION,
            schema_version=SCHEMA_VERSION,
            input_tokens=int(getattr(usage, "input_tokens", 0) or 0),
            output_tokens=int(getattr(usage, "output_tokens", 0) or 0),
            latency_ms=elapsed,
        )


def _response_refusal(response: Any) -> str | None:
    for output in getattr(response, "output", []) or []:
        for item in getattr(output, "content", []) or []:
            refusal = getattr(item, "refusal", None)
            if refusal:
                return str(refusal)
    return None


def build_provider(settings: Settings, *, client: Any | None = None) -> AnalysisProvider:
    if settings.analysis_provider == "fake":
        return FakeAnalysisProvider()
    if settings.analysis_provider == "disabled":
        return DisabledProvider()
    return OpenAIResponsesProvider(settings, client=client)
